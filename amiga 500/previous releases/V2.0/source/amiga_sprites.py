# the three colours of every family (12 bit)
COLOURS = {
    'bat': (0x214, 0x426, 0xc22),
    'bird': (0x112, 0x335, 0xfd6),
    'comet': (0xfa4, 0xfe8, 0xfff),
    'fly': (0x222, 0xfc4, 0x4cf),
    'cloud': (0x000, 0xbbd, 0xeef),
    'shuttle': (0x445, 0x889, 0xccd),
    'ship': (0xf84, 0x99a, 0xdde),
}


def family(name):
    for k in COLOURS:
        if name.startswith(k):
            return k
    raise KeyError(name)


def rows(name):
    if name.endswith('_l'):
        return [r[::-1] for r in FRAMES[name[:-2]].strip('\n').split('\n')]
    return FRAMES[name].strip('\n').split('\n')


def columns(name, double=False):
    """-> list per 16 pixel column of (plane0 words, plane1 words), height"""
    rs = rows(name)
    if double:
        rs = [r for r in rs for _ in (0, 1)]
    w = max(len(r) for r in rs)
    ncol = (w + 15) // 16
    cols = []
    for c in range(ncol):
        p0, p1 = [], []
        for r in rs:
            r = r.ljust(ncol * 16, '.')
            a = b = 0
            for i in range(16):
                ch = r[c * 16 + i]
                v = 0 if ch == '.' else int(ch)
                a = a << 1 | (v & 1)
                b = b << 1 | (v >> 1)
            p0.append(a)
            p1.append(b)
        cols.append((p0, p1))
    return cols, len(rs)
