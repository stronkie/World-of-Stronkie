;======================================================================
;  save and load (AmigaDOS files on the game disk)
;  "S4", part, room, score, moves_cnt, fragments, objects, rooms, flags[64],
;  checkpoint[69], object places, room exits, visited (as on the C64)
;======================================================================
ask_slot                            ; Z=1: slot 1-3 chosen (file name patched)
        lea     m_slot,a0
        bsr     print
        bsr     wait_key
        cmp.b   #'1',d0
        blo   .no
        cmp.b   #'3',d0
        bhi   .no
        move.b  d0,slot
        bsr     putchar
        moveq   #13,d0
        bsr     putchar
        moveq   #0,d0
        rts
.no     moveq   #13,d0
        bsr     putchar
        lea     m_ok,a0
        bsr     print
        moveq   #1,d0
        rts

save_name                           ; -> a0 = "Stronkie(2/3):SAVEn-..." of this part, d1 = disk
        moveq   #0,d0
        move.b  cur_chap,d0
        lea     part_disk-1,a0
        moveq   #0,d1
        tst.b   floppy
        beq     .hd                 ; from a hard disk: the current directory
        move.b  (a0,d0.w),d1
.hd     move.w  d1,-(sp)
        lea     savename,a1
        bsr     vol_prefix
        move.l  a1,save_short
        GETP    H_SAVEN,a0
.cp     move.b  (a0)+,(a1)+
        bne   .cp
        move.l  save_short,a0
        move.b  slot,4(a0)
        lea     savename,a0
        move.w  (sp)+,d1
        rts

vol_prefix                          ; d1 = disk 1/2 (0: none), a1 = buffer -> the volume name, a1 after it
        tst.b   d1
        beq     .x
        lea     vol1,a0
        cmp.b   #2,d1
        bne     .v3
        lea     vol2,a0
.v3     cmp.b   #3,d1
        bne     .cp
        lea     vol3,a0
.cp     move.b  (a0)+,(a1)+
        bne     .cp
        subq.l  #1,a1
.x      rts

disk_usable                         ; d1 = 0 (current directory) or disk 1-3 -> Z=0 if usable
        tst.b   floppy
        beq     .hd
        tst.w   d1
        beq     .no
        bra     vol_present
.hd     tst.w   d1                  ; from a hard disk: only the current directory
        beq     .yes
.no     moveq   #0,d0
        rts
.yes    moveq   #1,d0
        rts

vol_present                         ; d1 = disk 1-3 -> d0/Z=0 if that disk is in a drive
        movem.l d1-d4/a0-a3/a6,-(sp) ; (a volume node in the DOS list with a handler task)
        lea     vol1,a2
        cmp.w   #2,d1
        bne     .v3
        lea     vol2,a2
.v3     cmp.w   #3,d1
        bne     .v
        lea     vol3,a2
.v      move.l  execbase,a6
        jsr     _LVOForbid(a6)
        moveq   #0,d4
        move.l  dosbase,a0
        move.l  34(a0),d0           ; dl_Root
        beq     .x
        move.l  d0,a0
        move.l  24(a0),d0           ; rn_Info (BPTR)
        lsl.l   #2,d0
        beq     .x
        move.l  d0,a0
        move.l  4(a0),d0            ; di_DevInfo (BPTR)
.lp     lsl.l   #2,d0
        beq     .x
        move.l  d0,a0
        cmp.l   #2,4(a0)            ; DLT_VOLUME
        bne     .next
        tst.l   8(a0)               ; dl_Task: 0 = not in a drive
        beq     .next
        move.l  40(a0),d1           ; dl_Name (BSTR)
        lsl.l   #2,d1
        move.l  d1,a1
        moveq   #0,d2
        move.b  (a1)+,d2            ; length
        move.l  a2,a3
.c      move.b  (a3)+,d3
        cmp.b   #':',d3
        beq     .end
        subq.w  #1,d2
        bmi     .next
        move.b  (a1)+,d1
        or.b    #$20,d1             ; (any case)
        or.b    #$20,d3
        cmp.b   d1,d3
        beq     .c
        bra     .next
.end    tst.w   d2
        bne     .next
        moveq   #1,d4               ; found
        bra     .x
.next   move.l  (a0),d0             ; dl_Next (BPTR)
        bra     .lp
.x      jsr     _LVOPermit(a6)
        move.l  d4,d0
        movem.l (sp)+,d1-d4/a0-a3/a6
        tst.l   d0
        rts

slot_name                           ; a2 = part name suffix, d1 = disk -> savename
        lea     savename,a1
        bsr     vol_prefix
        move.b  #'S',(a1)+
        move.b  #'A',(a1)+
        move.b  #'V',(a1)+
        move.b  #'E',(a1)+
        move.b  slot,(a1)+
.cp     move.b  (a2)+,(a1)+
        bne   .cp
        rts

do_save
        bsr     ask_slot
        bne     .rts
        lea     m_saving,a0
        bsr     print
        lea     savebuf,a0
        move.b  #'S',(a0)+
        move.b  #'4',(a0)+          ; save format 4 (as the C64 V1.7)
        move.b  cur_chap,(a0)+
        move.b  room,(a0)+
        move.w  score,d0
        move.b  d0,(a0)+            ; little endian, as on the C64
        lsr.w   #8,d0
        move.b  d0,(a0)+
        move.w  moves_cnt,d0
        move.b  d0,(a0)+
        lsr.w   #8,d0
        move.b  d0,(a0)+
        move.b  frags,(a0)+
        move.l  part,a1
        move.b  H_NOBJ(a1),(a0)+
        move.b  H_NROOM(a1),(a0)+
        lea     flags,a1
        moveq   #63,d0
.f      move.b  (a1)+,(a0)+
        dbf     d0,.f
        lea     cp_flags,a1
        moveq   #63,d0
.cp     move.b  (a1)+,(a0)+
        dbf     d0,.cp
        move.w  cp_score,d0
        move.b  d0,(a0)+
        lsr.w   #8,d0
        move.b  d0,(a0)+
        move.w  cp_moves,d0
        move.b  d0,(a0)+
        lsr.w   #8,d0
        move.b  d0,(a0)+
        move.b  cp_frags,(a0)+
        move.l  a0,a2
        moveq   #1,d7               ; where every object is
.o      move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .r
        move.w  d7,d0
        bsr     obj_ptr
        move.b  1(a0),(a2)+
        addq.w  #1,d7
        bra   .o
.r      moveq   #1,d7               ; exits of every room (doors may have opened)
.rl     move.l  part,a0
        cmp.b   H_NROOM(a0),d7
        bhi   .v
        move.w  d7,d1
        bsr     room_ptr_d1
        moveq   #5,d0
.e      move.b  8(a0),(a2)+
        addq.l  #1,a0
        dbf     d0,.e
        addq.w  #1,d7
        bra   .rl
.v      move.b  visited,(a2)+
        move.l  a2,d0
        sub.l   #savebuf,d0
        move.l  d0,-(sp)
        bsr     scratch_slot        ; (as the C64's S0:SAVEn*)
        bsr     save_name
        moveq   #-1,d0
        tst.w   d1                  ; on a floppy: only if that disk is in a drive
        beq     .sv
        move.l  a0,-(sp)
        bsr     vol_present
        move.l  (sp)+,a0
        bne     .sv
        moveq   #-1,d0              ; that disk is not in a drive
        bra     .no
.sv     move.l  (sp),d0
        lea     savebuf,a1
        bsr     disk_save
.no     addq.l  #4,sp
        tst.l   d0
        bmi   .fail
        lea     m_saved,a0
        bsr     print
        move.l  save_short,a0
        bsr     print
        lea     m_quote_end,a0
        bra     print
.fail   moveq   #SFX_ERROR,d0
        bsr     play_sfx
        lea     m_savefail,a0
        bra     print
.rts    rts

do_restore                          ; Z=1 restored
        bsr     ask_slot
        bne     .ret1
        lea     m_loadsave,a0
        bsr     print
        bsr     find_save           ; SAVEn-<any part>
        tst.l   d0
        bmi     .none
        lea     savebuf,a0
        cmp.b   #'S',(a0)
        bne     .none
        cmp.b   #'4',1(a0)          ; save format 4
        bne     .none
        moveq   #0,d0
        move.b  2(a0),d0            ; load that part fresh, then put everything back
        bsr     reload_chapter
        lea     savebuf+11,a0
        lea     flags,a1
        moveq   #63,d0
.f      move.b  (a0)+,(a1)+
        dbf     d0,.f
        lea     cp_flags,a1
        moveq   #63,d0
.cp     move.b  (a0)+,(a1)+
        dbf     d0,.cp
        move.b  1(a0),d0            ; checkpoint score, moves_cnt, fragments
        lsl.w   #8,d0
        move.b  (a0),d0
        move.w  d0,cp_score
        move.b  3(a0),d0
        lsl.w   #8,d0
        move.b  2(a0),d0
        move.w  d0,cp_moves
        move.b  4(a0),cp_frags
        lea     savebuf,a0
        move.b  5(a0),d0
        lsl.w   #8,d0
        move.b  4(a0),d0
        move.w  d0,score
        move.b  7(a0),d0
        lsl.w   #8,d0
        move.b  6(a0),d0
        move.w  d0,moves_cnt
        move.b  8(a0),frags
        bsr     chapter_screen
        lea     savebuf+144,a2
        moveq   #1,d7
.o      move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .r
        move.w  d7,d0
        bsr     obj_ptr
        move.b  (a2)+,1(a0)
        addq.w  #1,d7
        bra   .o
.r      moveq   #1,d7
.rl     move.l  part,a0
        cmp.b   H_NROOM(a0),d7
        bhi   .v
        move.w  d7,d1
        bsr     room_ptr_d1
        moveq   #5,d0
.e      move.b  (a2)+,8(a0)
        addq.l  #1,a0
        dbf     d0,.e
        addq.w  #1,d7
        bra   .rl
.v      move.b  (a2)+,visited
        move.b  savebuf+3,room
        bsr     draw_status
        lea     m_restored,a0
        bsr     print
        bsr     look
        moveq   #0,d0
        rts
.none   moveq   #SFX_ERROR,d0
        bsr     play_sfx
        lea     m_nosave,a0
        bsr     print
.ret1   moveq   #1,d0
        rts

scratch_slot                        ; delete SAVEn-<every part>: current directory, every disk
        movem.l d2/a2,-(sp)
        bsr     dos_begin
        moveq   #0,d2
.disk   lea     save_names,a2
        move.w  d2,d1
        bsr     disk_usable
        beq     .nd
.lp     tst.b   (a2)
        beq   .nd
        move.w  d2,d1
        bsr     slot_name
        move.l  dosbase,a6
        move.l  #savename,d1
        jsr     _LVODeleteFile(a6)
        bra   .lp
.nd     addq.w  #1,d2
        cmp.w   #3,d2
        bls     .disk
        bsr     dos_end
        movem.l (sp)+,d2/a2
        rts

find_save                           ; -> savebuf filled, d0 = length or -1
        ; the save file of slot n can belong to any part, on any disk
        moveq   #0,d2
.disk   lea     save_names,a2
        move.w  d2,d1
        bsr     disk_usable
        beq     .nd
.lp     tst.b   (a2)
        beq   .nd
        move.w  d2,d1
        move.l  d2,-(sp)
        bsr     slot_name
        move.l  (sp)+,d2
        move.l  a2,-(sp)
        lea     savename,a0
        lea     savebuf,a1
        move.l  #SAVE_MAX,d0
        bsr     disk_load
        move.l  (sp)+,a2
        tst.l   d0
        bpl   .yes
        bra   .lp
.nd     addq.w  #1,d2
        cmp.w   #3,d2
        bls     .disk
        moveq   #-1,d0
.yes    rts

;======================================================================
;  AmigaDOS
;======================================================================
disk_load                           ; a0 = name, a1 = buffer, d0 = max -> d0 = length or -1
        movem.l d2-d7/a2-a6,-(sp)
        move.l  a1,a4
        move.l  d0,d5
        move.l  a0,d4
        bsr     dos_begin
        move.l  dosbase,a6
        move.l  d4,d1
        move.l  #MODE_OLDFILE,d2
        jsr     _LVOOpen(a6)
        move.l  d0,d6
        beq   .err
        move.l  d6,d1
        move.l  a4,d2
        move.l  d5,d3
        jsr     _LVORead(a6)
        move.l  d0,d7
        move.l  d6,d1
        jsr     _LVOClose(a6)
        bsr     dos_end
        move.l  d7,d0
        movem.l (sp)+,d2-d7/a2-a6
        rts
.err    bsr     dos_end
        moveq   #-1,d0
        movem.l (sp)+,d2-d7/a2-a6
        rts

disk_save                           ; a0 = name, a1 = data, d0 = length -> d0 = -1 on error
        movem.l d2-d7/a2-a6,-(sp)
        move.l  a1,a4
        move.l  d0,d5
        move.l  a0,d4
        bsr     dos_begin
        move.l  dosbase,a6
        move.l  d4,d1
        move.l  #MODE_NEWFILE,d2
        jsr     _LVOOpen(a6)
        move.l  d0,d6
        beq   .err
        move.l  d6,d1
        move.l  a4,d2
        move.l  d5,d3
        jsr     _LVOWrite(a6)
        move.l  d0,d7
        move.l  d6,d1
        jsr     _LVOClose(a6)
        bsr     dos_end
        cmp.l   d5,d7
        bne   .err2
        moveq   #0,d0
        movem.l (sp)+,d2-d7/a2-a6
        rts
.err    bsr     dos_end
.err2   moveq   #-1,d0
        movem.l (sp)+,d2-d7/a2-a6
        rts

dos_begin                           ; the disk driver needs the blitter
        move.b  #1,in_dos
        bsr     blit_wait
        move.l  gfxbase,a6
        jsr     _LVODisownBlitter(a6)
        rts

dos_end
        move.l  gfxbase,a6
        jsr     _LVOOwnBlitter(a6)
        jsr     _LVOWaitBlit(a6)
        clr.b   in_dos
        rts

;======================================================================
;  zx unpacker (zxpack.py): bits MSB first, interlaced Elias gamma
;  a0 = packed stream, a1 = destination
;======================================================================
unzx
        movem.l d2-d3/d7/a2,-(sp)
        move.b  #$80,d7
.lp     add.b   d7,d7               ; next bit
        bne   .b1
        move.b  (a0)+,d7
        addx.b  d7,d7
.b1     bcs   .match
        move.b  (a0)+,(a1)+         ; 0: a literal byte
        bra   .lp
.match  bsr   .gamma              ; 1: offset high byte + 1 (128 = end)
        cmp.w   #128,d0
        beq   .end
        subq.w  #1,d0
        lsl.w   #8,d0
        move.b  (a0)+,d0
        addq.w  #1,d0               ; offset = hi*256 + lo + 1
        move.l  a1,a2
        sub.l   d0,a2
        bsr   .gamma              ; length - 1
.cp     move.b  (a2)+,(a1)+
        dbf     d0,.cp
        bra   .lp
.end    movem.l (sp)+,d2-d3/d7/a2
        rts
.gamma  moveq   #1,d0
.g1     add.b   d7,d7
        bne   .g2
        move.b  (a0)+,d7
        addx.b  d7,d7
.g2     bcs   .g3
        add.b   d7,d7
        bne   .g4
        move.b  (a0)+,d7
        addx.b  d7,d7
.g4     addx.w  d0,d0
        bra   .g1
