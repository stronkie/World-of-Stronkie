rollback
        lea     cp_flags,a0
        lea     flags,a1
        moveq   #63,d0
.f      move.b  (a0)+,(a1)+
        dbf     d0,.f
        move.w  cp_score,score
        move.w  cp_moves,moves_cnt
        move.b  cp_frags,frags
        rts

