        moveq   #0,d2
.p      addq.w  #1,d2               ; digits left to print (at least 1)
.pl     move.b  (a2)+,d0
        bsr     putchar
        dbf     d2,.pl
        movem.l (sp)+,d2/a2
        rts

to_digits                           ; d0.w -> dig (5 ASCII digits)
        lea     dig+5,a0
        and.l   #$ffff,d0
        moveq   #4,d2
.lp     divu    #10,d0
        swap    d0
        add.b   #'0',d0
        move.b  d0,-(a0)
        clr.w   d0
        swap    d0
        dbf     d2,.lp
        rts

snapshot                            ; checkpoint at the start of every part
        lea     flags,a0
        lea     cp_flags,a1
        moveq   #63,d0
.f      move.b  (a0)+,(a1)+
        dbf     d0,.f
        move.w  score,cp_score
        move.w  moves_cnt,cp_moves
        move.b  frags,cp_frags
