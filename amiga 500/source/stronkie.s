; ---- a long offset field of the part header -> address register ---------
GETP    macro               ; \1 = header field, \2 = address register
        move.l  part,\2
        add.l   \1(\2),\2
        endm

;======================================================================
        section code,code
;======================================================================
start
        lea     bss_start,a1        ; clear all variables (Kickstart 1.x may not do it)
        move.l  #(bss_end-bss_start)/4-1,d1
.clr    clr.l   (a1)+
        subq.l  #1,d1
        bpl     .clr
        move.l  sp,stack_save
        move.l  4.w,a6
        move.l  a6,execbase
        sub.l   a1,a1
        jsr     _LVOFindTask(a6)
        move.l  d0,a4
        move.l  d0,mytask
        tst.l   172(a4)             ; pr_CLI: started from the Workbench?
        bne   .cli
        lea     92(a4),a0           ; pr_MsgPort: wait for the Workbench message
        jsr     _LVOWaitPort(a6)
        lea     92(a4),a0
        jsr     _LVOGetMsg(a6)
        move.l  d0,wbmsg
.cli    lea     dosname,a1
        jsr     _LVOOldOpenLibrary(a6)
        move.l  d0,dosbase
        beq     exit_wb
        lea     gfxname,a1
        jsr     _LVOOldOpenLibrary(a6)
        move.l  d0,gfxbase
        beq     exit_dos
        bsr     alloc_memory
        tst.l   d0
        bne     .mem
        bsr     say_nomem           ; not enough memory: say so in the CLI
        bra     exit_mem
.mem
        bsr     input_on            ; all keys come to the game from now on
        tst.l   d0
        beq     exit_mem
        bsr     audio_init          ; waveforms, Paula
        moveq   #1,d1               ; started from the floppy "Stronkie"? (else: a hard disk)
        bsr     vol_present
        sne     floppy
        bsr     video_on            ; copper lists, our own display (owns the blitter)
        bsr     load_sounds         ; sampled effects and speech (dos_begin/dos_end)
        bsr     alloc_cache         ; the picture cache gets the chip memory that is left
        tst.l   d0
        beq     no_cache
        bsr     vbl_on              ; music, sprites, colour cycling (vertical blank)

        bsr     game                ; returns when ESC is pressed on the title screen

        bsr     vbl_off
        bsr     audio_off
        bsr     video_off
        bsr     input_off
        bra     exit_mem
no_cache                            ; not enough chip memory: back to the CLI with a message
        bsr     audio_off
        bsr     video_off
        bsr     input_off
        bsr     say_nomem
exit_mem
        bsr     free_sounds
        bsr     free_memory
exit_gfx
        move.l  execbase,a6
        move.l  gfxbase,a1
        jsr     _LVOCloseLibrary(a6)
exit_dos
        move.l  execbase,a6
        move.l  dosbase,a1
        jsr     _LVOCloseLibrary(a6)
exit_wb
        move.l  execbase,a6
        move.l  wbmsg,d0
        beq   .done
        jsr     _LVOForbid(a6)
        move.l  wbmsg,a1
        jsr     _LVOReplyMsg(a6)
.done   move.l  stack_save,sp
        moveq   #0,d0
        rts

; ---- memory -------------------------------------------------------------
alloc_memory                        ; -> d0 = 0 if there is not enough memory
        move.l  execbase,a6
        move.l  #CHIP_SIZE,d0       ; copper lists, bitmaps, sprites, waveforms: chip memory
        move.l  #MEMF_CHIP|MEMF_CLEAR,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,p_chip
        beq   .fail
        lea     chip_offs,a0
        lea     p_cop_game,a1
        moveq   #11-1,d1
.po     move.l  p_chip,d0
        add.l   (a0)+,d0
        move.l  d0,(a1)+
        dbf     d1,.po
        move.l  #PART_MAX,d0
        move.l  #MEMF_CLEAR,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,part
        beq   .fail
        move.l  #SPEECH_MAX,d0      ; speech is unpacked here (chip memory: Paula plays it)
        move.l  #MEMF_CHIP,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,speech_buf
        beq   .fail
        move.l  #FILE_MAX,d0
        moveq   #0,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,filebuf
        beq   .fail
        move.l  #320*192,d0
        moveq   #0,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,chunky
        beq   .fail
        moveq   #1,d0
        rts
.fail   moveq   #0,d0
        rts

say_nomem                           ; "not enough memory": in the CLI, or in a window of its own
        movem.l d2-d4/a6,-(sp)      ; (started from the Workbench)
        move.l  dosbase,a6
        moveq   #0,d4
        jsr     _LVOOutput(a6)
        move.l  d0,d1
        bne     .w
        move.l  #con_name,d1
        move.l  #MODE_NEWFILE,d2
        jsr     _LVOOpen(a6)
        move.l  d0,d4
        beq     .x
        move.l  d0,d1
.w      move.l  #m_nomem,d2
        move.l  #m_nomem_end-m_nomem,d3
        jsr     _LVOWrite(a6)
        move.l  d4,d1
        beq     .x
        move.l  #400,d1             ; 8 seconds to read it
        jsr     _LVODelay(a6)
        move.l  d4,d1
        jsr     _LVOClose(a6)
.x      movem.l (sp)+,d2-d4/a6
        rts

chip_offs                           ; where every buffer is in the chip memory block
        dc.l    C_COP_GAME,C_COP_FS,C_PIC_BM,C_STATUS_BM,C_TEXT_BM,C_FS_BM
        dc.l    C_SPR_BUFS,C_SCROLL_BM,C_WAVES,C_NOISE_WAVE,C_SILENCE

CHIP_RESERVE = 40960                ; chip memory left free for AmigaDOS and the system

alloc_cache                         ; last of all: the picture cache, as many pictures as the
        move.l  execbase,a6         ; free chip memory allows -> d0 = 0: not even one
        moveq   #0,d7
        lea     cache_mem,a2
.cache  tst.w   d7                  ; (one picture is a must)
        beq     .must
        move.l  #MEMF_CHIP,d1
        jsr     _LVOAvailMem(a6)
        cmp.l   #PIC_BYTES+CHIP_RESERVE,d0
        blo     .cend
.must   move.l  #PIC_BYTES,d0
        move.l  #MEMF_CHIP,d1
        jsr     _LVOAllocMem(a6)
        move.l  d0,(a2)+
        beq   .cend
        addq.w  #1,d7
        cmp.w   #CACHE_SLOTS,d7
        bne   .cache
.cend   move.w  d7,ncache
        moveq   #0,d0
        move.w  d7,d0
        rts

free_memory
        move.l  execbase,a6
        move.l  p_chip,d0
        beq     .nc
        move.l  d0,a1
        move.l  #CHIP_SIZE,d0
        jsr     _LVOFreeMem(a6)
.nc
        lea     cache_mem,a2
        move.w  ncache,d7
        bra   .cf
.cl     move.l  (a2)+,a1
        move.l  #PIC_BYTES,d0
        jsr     _LVOFreeMem(a6)
.cf     dbf     d7,.cl
        move.l  chunky,d0
        beq   .f1
        move.l  d0,a1
        move.l  #320*192,d0
        jsr     _LVOFreeMem(a6)
.f1     move.l  speech_buf,d0
        beq   .f1b
        move.l  d0,a1
        move.l  #SPEECH_MAX,d0
        jsr     _LVOFreeMem(a6)
.f1b    move.l  filebuf,d0
        beq   .f2
        move.l  d0,a1
        move.l  #FILE_MAX,d0
        jsr     _LVOFreeMem(a6)
.f2     move.l  part,d0
        beq   .f3
        move.l  d0,a1
        move.l  #PART_MAX,d0
        jsr     _LVOFreeMem(a6)
.f3     rts

;======================================================================
;  the game (the same flow as the C64 version)
;======================================================================
game
restart
        bsr     show_menu           ; title picture, music, loads part 1 meanwhile
        moveq   #1,d0
        bsr     load_chapter
        bsr     menu_wait           ; N = new game, L = load a saved game
        move.b  d0,choice
        cmp.b   #KEY_ESC,d0
        beq     game_exit
        lea     flags,a0
        moveq   #63,d1
.cf     clr.b   (a0)+
        dbf     d1,.cf
        clr.w   score
        clr.w   moves_cnt
        clr.b   frags
        clr.b   lastbuf
        cmp.b   #'L',choice
        bne   rs_new
        bsr     chapter_screen
        bsr     do_restore
        beq   main_loop           ; restored
        bsr     begin_chapter       ; no saved game: start a new one
        lea     m_nosave,a0
        bsr     print
        bra   main_loop
rs_new  bsr     begin_chapter

main_loop
        bsr     input_line
        bsr     check_again
        bsr     parse
        tst.b   verb
        beq   .cmd
        tst.b   perr
        bne   .cmd
        addq.w  #1,moves_cnt            ; a real command: one move
.cmd    bsr     do_command
        bsr     draw_status
        tst.b   game_state
        bne   ml_state
        moveq   #0,d0
        bsr     run_actions         ; verb 0 = every-turn events
        bsr     draw_status
        tst.b   game_state
        beq   main_loop
ml_state
        cmp.b   #3,game_state
        bne   game_over
        bsr     more_prompt         ; read the last message first
        bsr     show_card           ; title card of the next part, shown while it loads
        moveq   #0,d0
        move.b  next_chap,d0
        bsr     load_chapter
        bsr     card_hold
        bsr     begin_chapter
        bra   main_loop

game_over
        bsr     music_stop
        move.b  game_state,d0
        cmp.b   #2,d0
        bne   .notdead
        moveq   #SND_DIED,d0        ; "You have died."
        bsr     speak_sound
        lea     m_dead,a0
        bsr     print
        GETP    H_QUIP,a0           ; a Sierra-style joke about your death
        bsr     print
        bsr     show_score
        lea     m_retry,a0
        bsr     print
        bsr     wait_key
        cmp.b   #'N',d0
        beq     restart
        bsr     rollback            ; back to the start of this part
        moveq   #0,d0
        move.b  cur_chap,d0
        bsr     reload_chapter
        bsr     begin_chapter
        bra     main_loop
.notdead
        cmp.b   #1,d0
        bne     restart             ; QUIT / F7: straight back to the title screen
        moveq   #SND_CONGRATS,d0    ; "Congratulations!"
        bsr     speak_sound
        lea     m_end,a0
        bsr     print
        bsr     show_score
        bsr     credits             ; rolling credits (only after the very end)
        lea     m_again,a0
        bsr     print
        bsr     wait_key
        bra     restart

game_exit
        rts

; ---- a new part --------------------------------------------------------
chapter_screen                      ; screen, status bar and music for the loaded part
        bsr     game_screen
        clr.b   game_state
        move.l  part,a0
        move.b  H_START(a0),room
        bsr     draw_status
        move.l  part,a1
        sub.l   a0,a0
        move.l  H_SONG(a1),d0       ; 0 = no music
        beq   .song
        lea     (a1,d0.l),a0
.song   bra     music_start

begin_chapter
        bsr     chapter_screen
        bsr     snapshot            ; TRY AGAIN restarts the part from here
        move.l  part,a0
        cmp.b   #1,H_NUM(a0)
        bne   .title
        lea     m_banner,a0
        bsr     print
.title  GETP    H_TITLE,a0
        bsr     print
        GETP    H_INTRO,a0
        bsr     print
        bra     look

; ---- loading a part ---------------------------------------------------
load_chapter                        ; d0 = part 1-17 -> file PARTnn, unpacked, pictures ready
        move.b  d0,packed_part
        and.l   #$ff,d0
        lea     part_disk-1,a0
        moveq   #0,d1
        move.b  (a0,d0.w),d1
        move.b  d1,want_disk
        lea     fname,a1
        bsr     vol_prefix          ; "Stronkie:" or "Stronkie2:"
        move.l  a1,fname_plain      ; (without it: from a hard disk, the current directory)
        move.l  #'PART',d1
        rol.l   #8,d1
        move.b  d1,(a1)+
        rol.l   #8,d1
        move.b  d1,(a1)+
        rol.l   #8,d1
        move.b  d1,(a1)+
        rol.l   #8,d1
        move.b  d1,(a1)+
        divu    #10,d0
        add.b   #'0',d0
        move.b  d0,(a1)+
        swap    d0
        add.b   #'0',d0
        move.b  d0,(a1)+
        clr.b   (a1)
.retry  tst.b   menu_on
        bne   .load               ; title screen or card on: load quietly behind it
        bsr     loading_screen
.load   move.l  fname_plain,a0      ; from a hard disk: the current directory
        tst.b   floppy
        beq     .open
        moveq   #0,d1               ; from floppies: is the disk in a drive?
        move.b  want_disk,d1
        bsr     vol_present
        beq     .err                ; no: PLEASE INSERT DISK n
        lea     fname,a0            ; "Stronkie2:PART06"
.open   move.l  filebuf,a1
        move.l  #FILE_MAX,d0
        bsr     disk_load           ; -> d0 = length, -1 = error
        tst.l   d0
        bmi   .err
        move.l  d0,packed_len
        bsr     unpack_part
        bne   .err
        bsr     part_ready
        rts
.err    clr.b   menu_on
        bsr     disk_error_screen   ; CANNOT FIND THE NEXT PART... PRESS A KEY
        bsr     wait_key
        bra   .retry

reload_chapter                      ; d0 = part: unpack it again if it is still in memory
        cmp.b   packed_part,d0
        bne     load_chapter
        move.l  d0,-(sp)
        bsr     unpack_part
        movem.l (sp)+,d0            ; (keeps the flags)
        bne     load_chapter
        bra     part_ready

unpack_part                         ; filebuf -> part; Z=1 ok
        clr.b   part_ok
        move.l  filebuf,a0          ; .l packed length, packed part, then the pictures
        move.l  (a0)+,d0
        lea     (a0,d0.l),a1
        move.l  a1,pic_blob
        move.l  part,a1
        bsr     unzx
        move.l  part,a0
        cmp.l   #'CHAP',(a0)
        rts

part_ready
        move.l  part,a0
        move.b  H_NUM(a0),cur_chap
        lea     flags,a0            ; every part has its own flags 0-55; 56-63 go
        moveq   #55,d1              ; along through the whole game
.cf     clr.b   (a0)+
        dbf     d1,.cf
        clr.b   visited
        bsr     cache_reset         ; pictures: decoded when needed / in the background
        move.b  #1,part_ok
        rts

;======================================================================
;  keyboard
;======================================================================
wait_key                            ; -> d0 = key
        bsr     flush_keys
.lp     bsr     idle_frame
        bsr     get_key
        beq   .lp
        rts

input_line
        clr.b   more_cnt
        clr.b   in_len
        bsr     clear_input_row
        moveq   #'>',d0
        moveq   #0,d1
        moveq   #INCOL,d2
        bsr     input_char
.key    moveq   #0,d1               ; blink the cursor
        move.b  in_len,d1
        addq.w  #2,d1
        moveq   #' ',d0
        btst    #4,frames+3
        beq   .off
        moveq   #$7f,d0             ; solid block
.off    moveq   #INCOL,d2
        bsr     input_char
        bsr     idle_frame
        bsr     get_key
        beq   .key
        cmp.b   #13,d0
        beq   .done
        cmp.b   #KEY_BS,d0
        beq   .del
        cmp.b   #$80,d0
        bhs   .fkey
        cmp.b   #$20,d0
        blo   .key
        cmp.b   #$5b,d0
        bhs   .key
        moveq   #0,d1
        move.b  in_len,d1
        cmp.b   #INPUT_MAX,d1
        bhs   .key
        lea     inbuf,a0
        move.b  d0,(a0,d1.w)
        addq.w  #2,d1
        moveq   #INCOL,d2
        bsr     input_char
        addq.b  #1,in_len
        moveq   #SFX_CLICK,d0
        bsr     play_sfx
        bra   .key
.fkey   bsr     fkey                ; F1/F3/F5/F7/HELP -> a command
        bne   .key
        bra   .done
.del    tst.b   in_len
        beq   .key
        moveq   #0,d1
        move.b  in_len,d1
        addq.w  #2,d1
        moveq   #' ',d0
        moveq   #INCOL,d2
        bsr     input_char          ; erase the cursor
        subq.b  #1,in_len
        bra   .key
.done   moveq   #0,d1
        move.b  in_len,d1
        lea     inbuf,a0
        clr.b   (a0,d1.w)
        bsr     clear_input_row
        move.b  #ECHOCOL,cur_col    ; echo the command in the text window
        moveq   #'>',d0
        bsr     putchar
        moveq   #' ',d0
        bsr     putchar
        lea     inbuf,a2
.echo   move.b  (a2)+,d0
        beq   .eend
        bsr     putchar
        bra   .echo
.eend   moveq   #13,d0
        bra     putchar

fkey                                ; d0 = key -> inbuf; Z=1 if it was a command key
        lea     fk_tab,a0
.lp     move.b  (a0)+,d1
        beq   .no
        cmp.b   d1,d0
        beq   .yes
.skip   tst.b   (a0)+
        bne   .skip
        bra   .lp
.yes    lea     inbuf,a1
        moveq   #0,d1
.cp     move.b  (a0)+,(a1)+
        beq   .end
        addq.b  #1,d1
        bra   .cp
.end    move.b  d1,in_len
        moveq   #0,d0               ; Z=1
        rts
.no     moveq   #1,d0               ; Z=0
        rts

;======================================================================
;  parser: up to two words, first four letters count
;======================================================================
parse
        clr.b   verb
        clr.b   noun
        clr.b   nwords
        clr.b   perr
        clr.b   inpos
.word   lea     inbuf,a0
        moveq   #0,d1
        move.b  inpos,d1
.skip   move.b  (a0,d1.w),d0
        beq     .ret
        cmp.b   #' ',d0
        bne   .copy
        addq.w  #1,d1
        bra   .skip
.copy   move.b  d1,wstart
        move.l  #'    ',wordbuf
        lea     wordbuf,a1
        moveq   #0,d2
.cl     move.b  (a0,d1.w),d0
        beq   .got
        cmp.b   #' ',d0
        beq   .got
        cmp.w   #4,d2
        bhs   .long
        move.b  d0,(a1,d2.w)
        addq.w  #1,d2
.long   addq.w  #1,d1
        bra   .cl
.got    move.b  d1,inpos
        lea     noise,a0
        bsr     lookup
        beq   .word               ; ignore THE, A, WITH ...
        tst.b   nwords
        bne   .second
        addq.b  #1,nwords
        lea     verbs,a0
        bsr     lookup
        bne   .v_unk
        move.b  d0,verb
        bra   .word
.v_unk  move.b  #1,perr
.ret    rts
.second cmp.b   #1,nwords
        bne   .ret
        addq.b  #1,nwords
        cmp.l   #'ALL ',wordbuf        ; TAKE ALL, DROP ALL
        bne   .noun
        move.b  #$fe,noun
        rts
.noun   GETP    H_NOUNS,a0
        bsr     lookup
        bne   .try_v
        move.b  d0,noun
        rts
.try_v  lea     verbs,a0            ; GO NORTH -> NORTH
        bsr     lookup
        bne   .n_unk
        cmp.b   #V_N,d0
        blo   .n_unk
        cmp.b   #V_D,d0
        bhi   .n_unk
        cmp.b   #V_GO,verb
        bne   .skipdir            ; PICK UP KEY: ignore the direction word
        move.b  d0,verb
        rts
.skipdir
        subq.b  #1,nwords
        bra     .word
.n_unk  move.b  #2,perr
        rts

lookup                              ; a0 = table of 4 chars + id, 0 ends -> Z=1 found, d0 = id
        move.l  wordbuf,d1
.lp     tst.b   (a0)
        beq   .no
        move.b  (a0),d0             ; the tables are not word aligned: compare bytes
        lsl.l   #8,d0
        move.b  1(a0),d0
        lsl.l   #8,d0
        move.b  2(a0),d0
        lsl.l   #8,d0
        move.b  3(a0),d0
        cmp.l   d0,d1
        beq   .yes
        addq.l  #5,a0
        bra   .lp
.yes    moveq   #0,d0
        move.b  4(a0),d0
        cmp.b   d0,d0               ; Z=1
        rts
.no     moveq   #1,d0               ; Z=0
        rts

;======================================================================
;  command execution
;======================================================================
do_command
        move.b  perr,d0
        beq   .ok
        move.l  d0,-(sp)
        moveq   #SFX_ERROR,d0
        bsr     play_sfx
        move.l  (sp)+,d0
        lea     m_huh,a0
        cmp.b   #1,d0
        beq   .e
        lea     m_word,a0
.e      bsr     print
        bra     print_badword
.ok     moveq   #0,d0
        move.b  verb,d0
        bne   .run
        rts
.run    bsr     run_actions
        bcc   builtin
        cmp.b   #V_HINT,verb
        bne   .done
        bra     hint_cost
.done   rts

; ---- built-in verbs ---------------------------------------------------
builtin
        move.b  verb,d0
        cmp.b   #V_N,d0
        blo   .notdir
        cmp.b   #V_D,d0
        bls     do_move
.notdir cmp.b   #V_GO,d0
        bne   .b1
        lea     m_where,a0
        bra     print
.b1     cmp.b   #V_LOOK,d0
        bne   .b2
        tst.b   noun
        bne     bi_exam
        bra     look
.b2     cmp.b   #V_TAKE,d0
        beq     do_take
        cmp.b   #V_DROP,d0
        beq     do_drop
        cmp.b   #V_INV,d0
        beq     do_inv
        cmp.b   #V_EXAM,d0
        beq     bi_exam
        cmp.b   #V_READ,d0
        beq     bi_exam
        cmp.b   #V_SEARCH,d0
        beq     bi_exam
        cmp.b   #V_WAIT,d0
        bne   .b6
        lea     m_wait,a0
        bra     print
.b6     cmp.b   #V_MAP,d0
        beq     do_map
        cmp.b   #V_SCORE,d0
        beq     show_score
        cmp.b   #V_QUIT,d0
        beq     do_quit
        cmp.b   #V_HINT,d0
        bne   .b8b
        lea     m_nohint,a0
        bra     print
.b8b    cmp.b   #V_SAVE,d0
        bhs     sys_verbs
bi_9    tst.b   noun
        bne   .b10
        lea     m_what,a0
        bra     print
.b10    lea     m_cant,a0
        bra     print

bi_exam tst.b   noun
        bne   .e1
        lea     m_what,a0
        bra     print
.e1     bsr     find_obj
        bcc     not_here
        move.l  8(a0),d0            ; examine text
        beq   .none
        move.l  part,a0
        add.l   d0,a0
        bra     print
.none   lea     m_nothing,a0
        bra     print

do_quit
        lea     m_sure,a0
        bsr     print
        bsr     wait_key
        cmp.b   #'Y',d0
        bne   .no
        move.b  #4,game_state
        rts
.no     lea     m_ok,a0
        bra     print

do_move                             ; d0 = verb 2-7
        sub.b   #V_N,d0
        and.w   #7,d0
        bsr     room_ptr
        move.b  8(a0,d0.w),d1       ; exits at +8
        bne   .go
        moveq   #SFX_ERROR,d0
        bsr     play_sfx
        lea     m_noway,a0
        bra     print
.go     move.b  d1,room
        bra     look

do_take
        move.b  noun,d0
        cmp.b   #$fe,d0
        beq     take_all
        tst.b   d0
        bne   .t1
        lea     m_what,a0
        bra     print
.t1     bsr     find_obj
        bcc     not_here
        cmp.b   #$ff,1(a0)
        bne   .t3
        lea     m_have,a0
        bra     print
.t3     btst    #0,2(a0)            ; flags: bit 0 = can be taken
        bne   .t4
        lea     m_cant_take,a0
        bra     print
.t4     move.b  #$ff,1(a0)
        moveq   #SFX_TAKE,d0
        bsr     play_sfx
        lea     m_taken,a0
        bra     print

do_drop
        move.b  noun,d0
        cmp.b   #$fe,d0
        beq     drop_all
        tst.b   d0
        bne   .d1
        lea     m_what,a0
        bra     print
.d1     bsr     find_obj
        bcc   .no
        cmp.b   #$ff,1(a0)
        bne   .no
        move.b  room,1(a0)
        moveq   #SFX_DROP,d0
        bsr     play_sfx
        lea     m_dropped,a0
        bra     print
.no     lea     m_donthave,a0
        bra     print

not_here
        lea     m_notsee,a0
        bra     print

do_inv
        lea     m_carry,a0
        bsr     print
        clr.b   cnt
        moveq   #1,d7
.lp     move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .end
        move.w  d7,d0
        bsr     obj_ptr
        cmp.b   #$ff,1(a0)
        bne   .nx
        addq.b  #1,cnt
        move.l  a0,-(sp)
        moveq   #' ',d0
        bsr     putchar
        moveq   #' ',d0
        bsr     putchar
        move.l  (sp)+,a0
        bsr     print_objname
        moveq   #13,d0
        bsr     putchar
.nx     addq.w  #1,d7
        bra   .lp
.end    tst.b   cnt
        bne   .rts
        lea     m_nothing2,a0
        bra     print
.rts    rts

print_objname                       ; a0 = object
        move.l  4(a0),a0
        add.l   part,a0
        bra     print

; ---- look: picture, description, objects, exits -------------------------
look
        bsr     room_ptr
        move.l  4(a0),a0            ; picture (in the blob)
        add.l   pic_blob,a0
        bsr     draw_picture        ; (also: sprites, colour cycling, visited)
        bsr     room_ptr
        move.l  (a0),a0
        add.l   part,a0
        bsr     print
        moveq   #1,d7               ; objects in the room
.lp     move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .exits
        move.w  d7,d0
        bsr     obj_ptr
        move.b  room,d0
        cmp.b   1(a0),d0
        bne   .nx
        btst    #1,2(a0)            ; bit 1 = scenery, not listed
        bne   .nx
        move.l  a0,-(sp)
        lea     m_there,a0
        bsr     print
        move.l  (sp)+,a0
        bsr     print_objname
        lea     m_here,a0
        bsr     print
.nx     addq.w  #1,d7
        bra   .lp
.exits  lea     m_exits,a0
        bsr     print
        bsr     room_ptr
        lea     8(a0),a2
        lea     dirnames,a3
        moveq   #0,d6
        moveq   #5,d7
.ex     move.b  (a3)+,d0
        tst.b   (a2)+
        beq   .exn
        addq.w  #1,d6
        bsr     putchar
        moveq   #' ',d0
        bsr     putchar
.exn    dbf     d7,.ex
        tst.w   d6
        bne   .end
        lea     m_none,a0
        bsr     print
.end    moveq   #13,d0
        bra     putchar

room_ptr                            ; -> a0 = entry of the current room
        moveq   #0,d1
        move.b  room,d1
room_ptr_d1
        subq.w  #1,d1
        lsl.w   #4,d1               ; 16 bytes a room
        GETP    H_ROOMS,a0
        add.w   d1,a0
        rts

obj_ptr                             ; d0.w = object 1.. -> a0 = entry
        move.w  d0,d1
        subq.w  #1,d1
        mulu    #OBJ_SIZE,d1
        GETP    H_OBJS,a0
        add.l   d1,a0
        rts

find_obj                            ; noun -> visible object (room first, then carried)
        moveq   #1,d7               ; C=1 found: a0 = entry, d7 = object
.lp     move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .carr
        move.w  d7,d0
        bsr     obj_ptr
        move.b  noun,d0
        cmp.b   (a0),d0
        bne   .nx
        move.b  room,d0
        cmp.b   1(a0),d0
        beq   .yes
.nx     addq.w  #1,d7
        bra   .lp
.carr   moveq   #1,d7
.lp2    move.l  part,a0
        cmp.b   H_NOBJ(a0),d7
        bhi   .no
        move.w  d7,d0
        bsr     obj_ptr
        move.b  noun,d0
        cmp.b   (a0),d0
        bne   .nx2
        cmp.b   #$ff,1(a0)
        beq   .yes
.nx2    addq.w  #1,d7
        bra   .lp2
.no     andi    #$fe,ccr            ; C=0
        rts
.yes    ori     #1,ccr              ; C=1
        rts

;======================================================================
;  action interpreter
;  entry: verb, noun (0 = any), length, conditions..., actions..., 0
;  d0 = verb to match (0 = every-turn events: all matching entries run)
;  returns C=1 when a command entry handled the input
;======================================================================
run_actions
        movem.l d2-d7/a2-a4,-(sp)
        move.b  d0,match_v
        clr.b   handled
        GETP    H_ACTS,a2
.lp     move.b  (a2),d0
        cmp.b   #$ff,d0
        bne   .1
        movem.l (sp)+,d2-d7/a2-a4
        tst.b   handled
        beq   .c0
        ori     #1,ccr
        rts
.c0     andi    #$fe,ccr
        rts
.1      cmp.b   match_v,d0
        bne   .next
        tst.b   d0
        beq   .try                ; events ignore the noun
        move.b  1(a2),d0
        beq   .try
        cmp.b   noun,d0
        bne   .next
.try    bsr     run_entry
        bcc   .next               ; conditions failed
        move.b  #1,handled
        tst.b   match_v
        bne   .stop               ; commands: first match only
        tst.b   game_state
        bne   .stop
.next   moveq   #0,d0
        move.b  2(a2),d0
        add.l   d0,a2
        bra   .lp
.stop   movem.l (sp)+,d2-d7/a2-a4
        ori     #1,ccr
        rts

run_entry                           ; a2 = entry; C=0 conditions failed, C=1 actions done
        clr.b   need_look
        lea     3(a2),a3
.lp     moveq   #0,d0
        move.b  (a3)+,d0
        bne   .op
        tst.b   need_look
        beq   .ok
        move.l  a2,-(sp)
        bsr     look
        move.l  (sp)+,a2
.ok     ori     #1,ccr
        rts
.fail   andi    #$fe,ccr
        rts
.op     cmp.b   #$20,d0
        bhs     .act
        ; ---- conditions
        cmp.b   #C_INROOM,d0
        bne   .c1
        move.b  (a3)+,d1
        cmp.b   room,d1
        beq   .lp
        bra   .fail
.c1     cmp.b   #C_FLAG,d0
        bne   .c2
        moveq   #0,d1
        move.b  (a3)+,d1
        lea     flags,a0
        tst.b   (a0,d1.w)
        bne   .lp
        bra   .fail
.c2     cmp.b   #C_NFLAG,d0
        bne   .c3
        moveq   #0,d1
        move.b  (a3)+,d1
        lea     flags,a0
        tst.b   (a0,d1.w)
        beq   .lp
        bra   .fail
.c3     move.b  d0,d4               ; object conditions: first argument is an object
        moveq   #0,d0
        move.b  (a3)+,d0
        bsr     obj_ptr
        move.b  1(a0),d5            ; where it is
        cmp.b   #C_HERE,d4
        bne   .c4
        bsr     is_here
        bcs   .lp
        bra   .fail
.c4     cmp.b   #C_NHERE,d4
        bne   .c5
        bsr     is_here
        bcc     .lp
        bra   .fail
.c5     cmp.b   #C_CARR,d4
        bne   .c6
        cmp.b   #$ff,d5
        beq     .lp
        bra   .fail
.c6     cmp.b   #C_NCARR,d4
        bne   .c7
        cmp.b   #$ff,d5
        bne     .lp
        bra   .fail
.c7     move.b  (a3)+,d1            ; C_OBJAT
        cmp.b   d5,d1
        beq     .lp
        bra     .fail

.act    cmp.b   #A_MSG,d0
        bne   .a1
        move.b  (a3)+,d0
        bsr     print_msg
        bra     .lp
.a1     cmp.b   #A_SET,d0
        bne   .a2
        moveq   #0,d1
        move.b  (a3)+,d1
        lea     flags,a0
        move.b  #1,(a0,d1.w)
        bra     .lp
.a2     cmp.b   #A_CLR,d0
        bne   .a3
        moveq   #0,d1
        move.b  (a3)+,d1
        lea     flags,a0
        clr.b   (a0,d1.w)
        bra     .lp
.a3     cmp.b   #A_MOVE,d0
        bne   .a4
        moveq   #0,d0
        move.b  (a3)+,d0
        bsr     obj_ptr
        move.b  (a3)+,d1
        cmp.b   #$fe,d1             ; $fe = the room you are in (a companion follows you)
        bne   .mv
        move.b  room,d1
.mv     move.b  d1,1(a0)
        bra     .lp
.a4     cmp.b   #A_GOTO,d0
        bne   .a5
        move.b  (a3)+,room
        move.b  #1,need_look
        bra     .lp
.a5     cmp.b   #A_EXIT,d0
        bne   .a6
        moveq   #0,d1
        move.b  (a3)+,d1            ; room
        bsr     room_ptr_d1
        moveq   #0,d0
        move.b  (a3)+,d0            ; direction 0-5
        move.b  (a3)+,8(a0,d0.w)    ; destination
        bra     .lp
.a6     cmp.b   #A_SCORE,d0
        bne   .a7
        moveq   #0,d0
        move.b  (a3)+,d0
        bsr     add_score
        bra     .lp
.a7     cmp.b   #A_CHAP,d0
        bne   .a8
        move.b  (a3)+,next_chap
        move.b  #3,game_state
        bra     .lp
.a8     cmp.b   #A_WIN,d0
        bne   .a9
        move.b  #1,game_state
        bra     .lp
.a9     cmp.b   #A_DIE,d0
        bne   .a10
        move.b  #2,game_state
        bra     .lp
.a10    cmp.b   #A_LOOK,d0
        bne   .a11
        move.b  #1,need_look
        bra     .lp
.a11    cmp.b   #A_SFX,d0
        bne   .a12
        move.b  (a3)+,d0
        bsr     play_sfx
        bra     .lp
.a12    cmp.b   #A_FRAG,d0
        bne   .a13
        bsr     found_fragment
        bra     .lp
.a13    cmp.b   #A_FLASH,d0
        bne   .a14
        move.b  (a3)+,flash_n
        bra     .lp
.a14    cmp.b   #A_TUNE,d0
        bne     .lp
        addq.l  #2,a3               ; (the C64 tune address: not used)
        move.l  part,a1
        move.l  H_TUNE(a1),d0
        beq     .lp
        lea     (a1,d0.l),a0
        bsr     music_start
        bra     .lp

is_here                             ; d5 = place: carried or the current room -> C=1
        cmp.b   #$ff,d5
        beq   .yes
        cmp.b   room,d5
        beq   .yes
        andi    #$fe,ccr
        rts
.yes    ori     #1,ccr
        rts

print_msg                           ; d0.b = message number 1..
        and.w   #$ff,d0
        GETP    H_SPEECH,a0         ; V1.1: NOVA speaks
.sp     move.w  (a0),d1
        beq     .ns
        cmp.w   d1,d0
        beq     .say
        addq.l  #8,a0
        bra     .sp
.say    move.l  4(a0),a0
        add.l   pic_blob,a0
        bsr     speak_clip
.ns
        subq.w  #1,d0
        lsl.w   #2,d0
        GETP    H_MSGS,a0
        move.l  (a0,d0.w),a0
        add.l   part,a0
        bra     print

;======================================================================
;  TAKE ALL / DROP ALL, hints, fragments, checkpoint
;======================================================================
take_all
        clr.b   all_cnt
        move.w  #1,all_i
.lp     move.l  part,a0
        move.w  all_i,d0
        cmp.b   H_NOBJ(a0),d0
        bhi   .end
        bsr     obj_ptr
        move.b  room,d0
        cmp.b   1(a0),d0
        bne   .nx
        move.b  2(a0),d0
        and.b   #3,d0
        cmp.b   #1,d0               ; takeable and not scenery
        bne   .nx
        addq.b  #1,all_cnt
        move.b  (a0),noun
        bsr     print_objname
        lea     m_colon,a0
        bsr     print
        moveq   #V_TAKE,d0
        bsr     run_actions         ; puzzles that react to taking it
        bcs   .nx
        move.w  all_i,d0
        bsr     obj_ptr
        move.b  #$ff,1(a0)
        moveq   #SFX_TAKE,d0
        bsr     play_sfx
        lea     m_taken,a0
        bsr     print
.nx     tst.b   game_state
        bne   .end
        addq.w  #1,all_i
        bra   .lp
.end    move.b  #$fe,noun
        tst.b   all_cnt
        bne   .rts
        lea     m_nothing_take,a0
        bra     print
.rts    rts

drop_all
        clr.b   all_cnt
        move.w  #1,all_i
.lp     move.l  part,a0
        move.w  all_i,d0
        cmp.b   H_NOBJ(a0),d0
        bhi   .end
        bsr     obj_ptr
        cmp.b   #$ff,1(a0)
        bne   .nx
        addq.b  #1,all_cnt
        move.b  (a0),noun
        bsr     print_objname
        lea     m_colon,a0
        bsr     print
        moveq   #V_DROP,d0
        bsr     run_actions
        bcs   .nx
        move.w  all_i,d0
        bsr     obj_ptr
        move.b  room,1(a0)
        moveq   #SFX_DROP,d0
        bsr     play_sfx
        lea     m_dropped,a0
        bsr     print
.nx     tst.b   game_state
        bne   .end
        addq.w  #1,all_i
        bra   .lp
.end    move.b  #$fe,noun
        tst.b   all_cnt
        bne   .rts
        lea     m_nothing2,a0
