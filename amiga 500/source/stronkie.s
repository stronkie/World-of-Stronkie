;======================================================================
;  THE WORLD OF STRONKIE  V2.2  -  Amiga 500 version
;  Text & graphics adventure, ported from the Commodore 64 original
;  Created By Mark Stronks
;
;  Assembler : vasm (Motorola syntax)
;              vasmm68k_mot -Fhunkexe -nosym -o Stronkie stronkie.s
;  Machine   : Amiga 500, 68000, OCS/ECS (Fat Agnus), 1 MB chip memory
;  Disk      : Stronkie (this program), MENU, PART01-PART17, s/startup-sequence
;
;  The game keeps the operating system alive (so it can load and save
;  with AmigaDOS) but drives the hardware itself:
;    copper   - its own display lists: per-line sky gradients, raster
;               bars, palette fades, colour cycling, copper bars
;    blitter  - text window scrolling, picture copies, the scroller
;    sprites  - moving creatures and ships, 2-3 hardware sprites each
;    Paula    - 3 voice music + 1 voice sound effects, software ADSR
;    input    - an input.device handler (priority 100) takes all keys
;
;  Files: stronkie.s (this file: start-up, game logic), video.s, audio.s,
;         data.s (texts, verbs, font), tables.i (generated by the build)
;======================================================================

